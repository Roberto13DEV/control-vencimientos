CREATE DATABASE IF NOT EXISTS control_vencimientos_nuevo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE control_vencimientos_nuevo;

CREATE TABLE usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario VARCHAR(50) NOT NULL UNIQUE,
 clave VARCHAR(255) NOT NULL,
 rol ENUM('admin','empleado') NOT NULL DEFAULT 'empleado',
 activo TINYINT(1) NOT NULL DEFAULT 1,
 creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE productos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 codigo VARCHAR(30),
 producto VARCHAR(120) NOT NULL,
 categoria VARCHAR(80),
 proveedor VARCHAR(120),
 lote VARCHAR(50),
 cantidad INT UNSIGNED NOT NULL DEFAULT 0,
 tiene_cambio TINYINT(1) NOT NULL DEFAULT 0,
 fecha_cambio DATE NULL,
 producto_origen_id INT UNSIGNED NULL,
 vencimiento DATE NOT NULL,
 creado TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 actualizado TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX (producto), INDEX (vencimiento)
) ENGINE=InnoDB;

CREATE TABLE historial (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id INT UNSIGNED NULL,
 usuario VARCHAR(50) NOT NULL,
 accion VARCHAR(200) NOT NULL,
 fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
 INDEX (fecha)
) ENGINE=InnoDB;
